def main() -> None:
    header()
    try:
        prices, meta = sidebar_data()
    except QuantRiskError as exc:
        st.error(f"Could not load prices: {exc}", icon=":material/error:")
        st.markdown("You can still explore the app with the **Sample data** source.")
        st.stop()
    if prices is None:
        landing(meta)
        st.stop()

    assets, weights, benchmark = sidebar_portfolio(prices, meta)
    settings = sidebar_assumptions(prices, meta)
    if not assets:
        st.warning("Select at least one asset in the sidebar.", icon=":material/warning:")
        st.stop()

    cfg = AnalysisConfig(assets=tuple(assets), weights=weights, benchmark=benchmark, **settings)
    try:
        with st.spinner("Running analysis…"):
            result = run_analysis(prices, cfg)
    except QuantRiskError as exc:
        st.error(str(exc), icon=":material/error:")
        st.stop()
    except Exception as exc:  # unexpected: show the details instead of failing silently
        st.error("An unexpected error occurred while analysing the data.", icon=":material/error:")
        st.exception(exc)
        st.stop()

    theme = chart_theme()
    source_banner(result, meta)
    kpis(result)
    # Deep links: ?tab=risk opens the Risk tab directly.
    requested = TAB_SLUGS.get(str(st.query_params.get("tab", "")).lower())
    try:
        tabs = st.tabs(TAB_NAMES, default=TAB_NAMES[requested] if requested is not None else None)
    except TypeError:  # Streamlit versions without the `default` argument
        tabs = st.tabs(TAB_NAMES)
    with tabs[0]:
        tab_performance(result, theme)
    with tabs[1]:
        tab_risk(result, theme)
    with tabs[2]:
        tab_allocation(result, theme)
    with tabs[3]:
        tab_periods(result, theme)
    with tabs[4]:
        tab_data(result)
    with tabs[5]:
        tab_methodology()


main()
