def kpis(result: AnalysisResult) -> None:
    s = result.summary
    p = s["Portfolio"]
    b = s.get("Benchmark")
    bv = (lambda k: b[k]) if b is not None else (lambda k: None)
    c = result.config.confidence

    row1 = st.columns(4)
    row1[0].metric("Cumulative return", pct(p.cumulative_return), delta(p.cumulative_return, bv("cumulative_return")),
                   help="Total compounded return over the whole sample.")
    row1[1].metric("Annualised return", pct(p.annualized_return), delta(p.annualized_return, bv("annualized_return")),
                   help="Geometric average yearly return (CAGR).")
    row1[2].metric("Annualised volatility", pct(p.annualized_volatility),
                   delta(p.annualized_volatility, bv("annualized_volatility")), delta_color="inverse",
                   help="Standard deviation of periodic returns scaled by √(periods per year).")
    row1[3].metric(f"Sharpe ratio (rf {result.config.risk_free_rate:.2%})", num(p.sharpe_ratio),
                   delta(p.sharpe_ratio, bv("sharpe_ratio"), as_pct=False),
                   help="Mean excess return / volatility of excess returns, annualised.")

    row2 = st.columns(4)
    row2[0].metric("Maximum drawdown", pct(p.max_drawdown), delta(p.max_drawdown, bv("max_drawdown")),
                   help="Largest peak-to-trough fall in portfolio value.")
    row2[1].metric(f"1-period VaR {c:.1%}", pct(p.historical_var), delta(p.historical_var, bv("historical_var")),
                   delta_color="inverse",
                   help="Historical Value at Risk: loss not exceeded in this share of periods (positive = loss).")
    row2[2].metric(f"Expected Shortfall {c:.1%}", pct(p.historical_es), delta(p.historical_es, bv("historical_es")),
                   delta_color="inverse", help="Average loss in the periods beyond the VaR threshold.")
    if result.relative is not None:
        row2[3].metric("Beta to benchmark", num(result.relative["beta"]),
                       help="Sensitivity to benchmark moves: cov(rp, rb) / var(rb).")
    else:
        row2[3].metric("Effective number of assets", num(result.concentration["effective_number_of_assets"], 1),
                       help="1 / Σ w², the number of equal-weight positions with the same concentration.")


