def sidebar_data() -> tuple[pd.DataFrame | None, dict]:
    st.sidebar.header("1 · Data")
    source = st.sidebar.radio("Price source", list(SOURCES), format_func=SOURCES.get, key="source")

    if source == "sample":
        st.sidebar.caption(
            f"Synthetic adjusted prices generated by `src/sample_data.py` (seed {SEED}). "
            "**Not real market data.** Works offline."
        )
        return cached_sample(), {"key": "sample", "kind": "sample", "benchmark": SAMPLE_BENCHMARK,
                                 "label": "Synthetic sample data (not real market prices)"}

    if source == "upload":
        st.sidebar.download_button(
            "Download CSV template", make_csv_template(), file_name="price_template.csv",
            mime="text/csv", width="stretch",
        )
        st.sidebar.caption("Wide format: `Date` (YYYY-MM-DD) plus one column of adjusted close prices per ticker.")
        upload = st.sidebar.file_uploader("Price file (.csv)", type=["csv"])
        if upload is None:
            return None, {"kind": "upload"}
        prices = cached_upload(upload.getvalue())
        bench = next((c for c in ("BENCHMARK", "SPY", "^GSPC", "ACWI", "VT") if c in prices.columns), None)
        return prices, {"key": f"upload::{upload.name}", "kind": "upload", "benchmark": bench,
                        "label": f"Uploaded file: {upload.name}"}

    with st.sidebar.form("yahoo_form"):
        tickers = st.text_input("Tickers", "AAPL, MSFT, JNJ, TLT, GLD", help="Comma-separated Yahoo symbols.")
        benchmark = st.text_input("Benchmark ticker (optional)", "SPY")
        c1, c2 = st.columns(2)
        start = c1.date_input("From", dt.date(2015, 1, 1), max_value=dt.date.today())
        end = c2.date_input("To", dt.date.today(), max_value=dt.date.today())
        submitted = st.form_submit_button("Download prices", width="stretch", type="primary")
    st.sidebar.caption(
        "Adjusted closes via the unofficial `yfinance` library. Availability and usage are subject to "
        "Yahoo's terms, and the data may contain errors or gaps."
    )
    if submitted:
        symbols = clean_tickers(tickers)
        bench_symbol = clean_tickers(benchmark)[0] if benchmark.strip() else None
        all_symbols = tuple(dict.fromkeys(symbols + ([bench_symbol] if bench_symbol else [])))
        with st.spinner("Downloading prices from Yahoo Finance…"):
            prices, failed, retrieved = cached_yahoo(all_symbols, start, end)
        st.session_state["yahoo"] = {"prices": prices, "failed": failed, "retrieved": retrieved,
                                     "benchmark": bench_symbol, "symbols": all_symbols}

    data = st.session_state.get("yahoo")
    if data is None:
        return None, {"kind": "yahoo"}
    if data["failed"]:
        st.sidebar.warning(f"No data returned for: {', '.join(data['failed'])}")
    bench = data["benchmark"] if data["benchmark"] in data["prices"].columns else None
    return data["prices"], {
        "key": "yahoo::" + ",".join(data["symbols"]), "kind": "yahoo", "benchmark": bench,
        "label": f"Yahoo Finance adjusted closes, retrieved {data['retrieved']:%Y-%m-%d %H:%M} UTC",
    }


def window_options(ppy: int) -> dict[int, str]:
    spans = {"1 month": 1 / 12, "3 months": 0.25, "6 months": 0.5, "1 year": 1.0, "2 years": 2.0}
    out = {}
    for label, years in spans.items():
        w = int(round(ppy * years))
        if w >= 3 and w not in out:
            out[w] = f"{label} ({w} periods)"
    return out


def sidebar_portfolio(prices: pd.DataFrame, meta: dict) -> tuple[list[str], dict[str, float], str | None]:
    st.sidebar.header("2 · Portfolio")
    key = meta["key"]
    columns = list(prices.columns)
    bench_options = ["(none)"] + columns
    default_bench = meta.get("benchmark")
    bench_choice = st.sidebar.selectbox(
        "Benchmark", bench_options, key=f"bench::{key}",
        index=bench_options.index(default_bench) if default_bench in columns else 0,
        help="Used for relative performance, beta and the market-regime classification.",
    )
    benchmark = None if bench_choice == "(none)" else bench_choice

    candidates = [c for c in columns if c != benchmark]
    if meta["kind"] == "sample":
        default_assets = [a for a in SAMPLE_DEFAULT_WEIGHTS if a in candidates]
    else:
        default_assets = candidates[:10]
    assets = st.sidebar.multiselect("Assets", candidates, default=default_assets, key=f"assets::{key}")
    if not assets:
        return [], {}, benchmark

    equal = round(100.0 / len(assets), 2)

    def reset_equal() -> None:
        for a in assets:
            st.session_state[f"w::{key}::{a}"] = equal

    st.sidebar.caption("Weights in % (long-only). Totals other than 100% are rescaled proportionally.")
    weights = {}
    for a in assets:
        wkey = f"w::{key}::{a}"
        if wkey not in st.session_state:
            st.session_state[wkey] = SAMPLE_DEFAULT_WEIGHTS.get(a, equal) if meta["kind"] == "sample" else equal
        weights[a] = st.sidebar.number_input(a, min_value=0.0, max_value=10_000.0, step=1.0, format="%.2f", key=wkey)
    total = sum(weights.values())
    c1, c2 = st.sidebar.columns([1, 1])
    c1.markdown(f"**Total: {total:.2f}%**")
    c2.button("Equal weights", on_click=reset_equal, width="stretch")
    return assets, {a: w / 100.0 for a, w in weights.items()}, benchmark


def sidebar_assumptions(prices: pd.DataFrame, meta: dict) -> dict:
    st.sidebar.header("3 · Period & assumptions")
    key = meta["key"]
    first, last = prices.index[0].date(), prices.index[-1].date()
    c1, c2 = st.sidebar.columns(2)
    start = c1.date_input("Start", first, min_value=first, max_value=last, key=f"start::{key}")
    end = c2.date_input("End", last, min_value=first, max_value=last, key=f"end::{key}")

    rebalance = st.sidebar.selectbox(
        "Rebalancing", list(REBALANCE_OPTIONS), index=1, format_func=REBALANCE_OPTIONS.get,
        help="When weights are reset to target. Between rebalances they drift with performance. "
             "Transaction costs are ignored.",
    )
    rf = st.sidebar.number_input(
        "Risk-free rate (% per year)", min_value=-5.0, max_value=25.0, value=2.0, step=0.25,
        help="Annual effective rate, converted to a per-period rate by compounding. Used for Sharpe and alpha.",
    )
    confidence = st.sidebar.select_slider(
        "VaR / ES confidence", options=[0.90, 0.95, 0.975, 0.99], value=0.95, format_func=lambda c: f"{c:.1%}",
    )
    value = st.sidebar.number_input(
        "Portfolio value", min_value=1_000.0, value=1_000_000.0, step=100_000.0, format="%.0f",
        help="Initial investment for the growth chart; converts VaR/ES into money.",
    )

    try:
        detected = infer_frequency(prices.index)
    except QuantRiskError:
        detected = None
    with st.sidebar.expander("Advanced: windows, missing data, annualisation"):
        ppy_options = {0: f"Auto ({detected.label}, {detected.periods_per_year}/yr)" if detected else "Auto",
                       252: "252 (trading days)", 365: "365 (calendar days)", 52: "52 (weekly)", 12: "12 (monthly)"}
        ppy_choice = st.selectbox("Periods per year", list(ppy_options), format_func=ppy_options.get)
        ppy = ppy_choice or (detected.periods_per_year if detected else 252)
        options = window_options(ppy)
        keys = list(options)

        def pick(target: int) -> int:
            return keys.index(min(keys, key=lambda w: abs(w - target)))

        vol_window = st.selectbox("Rolling volatility window", keys, index=pick(round(ppy / 4)),
                                  format_func=options.get)
        sharpe_window = st.selectbox("Rolling Sharpe window", keys, index=pick(ppy), format_func=options.get)
        var_window = st.selectbox("VaR backtest look-back", keys, index=pick(ppy), format_func=options.get)
        policy = st.radio(
            "Missing prices", ["drop", "ffill"],
            format_func={"drop": "Drop incomplete dates (recommended)", "ffill": "Forward-fill short gaps"}.get,
            help="Dropping keeps cumulative returns exact. Forward-filling inserts 0% returns and slightly "
                 "understates volatility. Neither option back-fills before an asset's first price.",
        )
        ffill_limit = st.number_input("Max consecutive forward-filled dates", 1, 10, 3, disabled=policy != "ffill")

    return {
        "start": pd.Timestamp(start), "end": pd.Timestamp(end), "rebalance": rebalance,
        "risk_free_rate": rf / 100.0, "confidence": confidence, "portfolio_value": float(value),
        "periods_per_year": ppy_choice or None, "vol_window": vol_window, "sharpe_window": sharpe_window,
        "var_window": var_window, "missing_policy": policy, "ffill_limit": int(ffill_limit),
    }


