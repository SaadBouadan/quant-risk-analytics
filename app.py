def is_missing(x) -> bool:
    return x is None or (isinstance(x, float) and pd.isna(x))


def pct(x, digits: int = 2) -> str:
    return "n/a" if is_missing(x) else f"{x:.{digits}%}"


def num(x, digits: int = 2) -> str:
    return "n/a" if is_missing(x) else f"{x:,.{digits}f}"


def money(x) -> str:
    return "n/a" if is_missing(x) else f"{x:,.0f}"


def day(x) -> str:
    return "—" if x is None else f"{pd.Timestamp(x):%Y-%m-%d}"


def delta(port: float, bench: float | None, *, as_pct: bool = True) -> str | None:
    if bench is None or is_missing(bench) or is_missing(port):
        return None
    d = port - bench
    return f"{d * 100:+.2f} pp vs benchmark" if as_pct else f"{d:+.2f} vs benchmark"


